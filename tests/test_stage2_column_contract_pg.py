"""Validate strict legacy paper columns against SQLAlchemy's actual PostgreSQL DDL.
Only a disposable database named test is allowed.
"""
import os
import pytest
from sqlalchemy import create_engine, text
from app.paper_legacy_column_contract import inspect_legacy_paper_columns


# Local aggregate runs may omit PostgreSQL; CI must still supply its test URL.
pytestmark = pytest.mark.skipif(
    not os.getenv("TEST_POSTGRES_URL") and not os.getenv("CI"),
    reason="Disposable PostgreSQL required for local execution",
)

def test_real_orm_paper_schema_and_detect_nullable_regression():
    url=os.environ["TEST_POSTGRES_URL"]
    assert url.endswith("/test") and "127.0.0.1" in url
    engine=create_engine(url)
    with engine.begin() as con:
        assert con.scalar(text("SELECT current_database()"))=="test"
    # This test builds the original legacy Float schema from a deliberate
    # legacy-only definition, not the current Numeric ORM model.
    with engine.begin() as con:
        con.execute(text("""CREATE TABLE paper_accounts(
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            cash double precision NOT NULL, currency varchar(8) NOT NULL)"""))
        con.execute(text("""CREATE TABLE paper_trades(
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            account_id integer NOT NULL REFERENCES paper_accounts(id),
            symbol varchar(32) NOT NULL, side varchar(4) NOT NULL,
            quantity double precision NOT NULL, price double precision NOT NULL,
            fee double precision NOT NULL, executed_at timestamptz NOT NULL)"""))
    try:
        assert inspect_legacy_paper_columns(engine)=={"ready":True,"errors":[]}
        with engine.begin() as con:
            con.execute(text("ALTER TABLE paper_trades ALTER COLUMN fee DROP NOT NULL"))
        result=inspect_legacy_paper_columns(engine)
        assert not result["ready"]
        assert "NULLABILITY_MISMATCH:paper_trades.fee" in result["errors"]
    finally:
        with engine.begin() as con:
            con.execute(text("DROP TABLE paper_trades"))
            con.execute(text("DROP TABLE paper_accounts"))
        engine.dispose()
